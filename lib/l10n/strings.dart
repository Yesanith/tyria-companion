  final AppLang lang;

  String t(String key, [Map<String, Object?>? args]) {
    var text = _strings[lang.code]?[key] ?? _strings['en']![key] ?? key;
    args?.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
    return text;
  }
}

